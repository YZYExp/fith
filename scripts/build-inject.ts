/** Bundle src/inject/entry.ts into src/inject/bundle.generated.ts (a string the Node backend injects). */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export async function injectSource(): Promise<string> {
  const res = await build({
    entryPoints: [resolve('src/inject/entry.ts')],
    bundle: true,
    format: 'iife',
    target: 'chrome110',
    write: false,
    logLevel: 'silent',
  });
  return res.outputFiles[0]!.text;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const code = await injectSource();
  const dest = resolve('src/inject/bundle.generated.ts');
  writeFileSync(dest, `// Generated by scripts/build-inject.ts — do not edit.\nexport default ${JSON.stringify(code)};\n`);
  console.error(`injected bundle written to ${dest} (${(code.length / 1024).toFixed(0)} KB)`);
}
