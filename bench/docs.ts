/** `pnpm bench:docs` — regenerate docs/bench-corpus.md from bench/corpus.ts + bench/baseline.json. */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { CORPUS } from './corpus.js';

const base: Record<string, any> = existsSync('bench/baseline.json') ? JSON.parse(readFileSync('bench/baseline.json', 'utf8')) : {};
const pct = (v?: number, d = 2) => (v === undefined ? '–' : (v * 100).toFixed(d) + '%');
const row = (t: (typeof CORPUS)[number]) => {
  const b = base[t.id] || {};
  return `| \`${t.id}\` | ${t.kind === 'live' ? `<${t.src}>` : `bench/pages/${t.src}`} | ${t.width}×${t.height} | ${pct(b.ratio)} | ${pct(b.contentRatio, 1)} | ${pct(b.textCoverage, 0)} | ${pct(b.rasterAreaFrac, 0)} | ${b.nodes ?? '–'} |`;
};
const head = '| id | source | viewport | diff | content diff | text cov | raster area | nodes |\n|---|---|---|---|---|---|---|---|';
const out = `# Benchmark corpus

_Generated by \`pnpm bench:docs\` from \`bench/corpus.ts\` and \`bench/baseline.json\` — do not edit by hand.
Experiment history lives in [bench-log.md](bench-log.md); raw snapshots in \`bench/history/\`._

Metrics: **diff** = differing pixels / all pixels; **content diff** = differing / non-background pixels;
**text cov** = vector text chars ÷ rendered DOM text chars; **raster area** = area of raster-fallback nodes ÷ viewport.
Live pages drift between runs (ads, rotating stories) — use \`pnpm bench --repeat=3\` for a median.

## Live sites (${CORPUS.filter((t) => t.kind === 'live').length})
${head}
${CORPUS.filter((t) => t.kind === 'live').map(row).join('\n')}

## Real UI libraries from npm (${CORPUS.filter((t) => t.kind === 'local').length})
Pinned in \`bench/fetch.ts\`; pages in \`bench/pages/\`.

${head}
${CORPUS.filter((t) => t.kind === 'local').map(row).join('\n')}
`;
writeFileSync(resolve('docs/bench-corpus.md'), out);
console.error('wrote docs/bench-corpus.md');
